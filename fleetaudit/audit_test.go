	if err := os.MkdirAll(filepath.Join(repoDir, ".git"), 0755); err != nil {
		t.Fatal(err)
	}

	report := Audit(dir)
	if report.TotalRepos != 1 {
		t.Fatalf("TotalRepos = %d, want 1", report.TotalRepos)
	}
