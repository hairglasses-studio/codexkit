// writeAuditFile writes content to base/name, creating parent dirs as needed.
func writeAuditFile(t *testing.T, base, name, content string) {
	t.Helper()
	path := filepath.Join(base, name)
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}
}

// setupBaselineCompliantRepo builds a repo that passes baselineguard.Check
// so a fleetaudit test can isolate the behavior under test (e.g. mcp_sync)
// without unrelated baseline findings failing the repo first.
func setupBaselineCompliantRepo(t *testing.T, dir string) {
	t.Helper()
	writeAuditFile(t, dir, "AGENTS.md", "# Test\n\n> Canonical instructions: AGENTS.md\n")
	writeAuditFile(t, dir, "CLAUDE.md", "# Test\n\nThis repo uses [AGENTS.md](AGENTS.md) as the canonical instruction file.\n")
	writeAuditFile(t, dir, ".claude/settings.json", "{}\n")
	writeAuditFile(t, dir, ".agents/hooks.json", "{}\n")
	writeAuditFile(t, dir, ".agents/agents/reviewer/agent.md", "---\nname: reviewer\ndescription: Review changes.\n---\n")
	writeAuditFile(t, dir, ".codex/config.toml", "approval_policy = \"on-request\"\n")
	writeAuditFile(t, dir, ".codex/agents/reviewer.toml", `name = "reviewer"`)
	writeAuditFile(t, dir, ".codex/agents/repo_explorer.toml", `name = "repo_explorer"`)

	surface, _ := json.Marshal(map[string]any{
		"version": 1,
		"skills":  []map[string]any{{"name": "test_skill"}},
	})
	writeAuditFile(t, dir, ".agents/skills/surface.yaml", string(surface))
	writeAuditFile(t, dir, ".agents/skills/test_skill/SKILL.md", "---\nname: test_skill\ndescription: \"Core build, test, release, and maintenance workflow for the test repo.\"\nallowed-tools:\n  - Bash\n---\n# Test\n")
	writeAuditFile(t, dir, ".claude/skills/test_skill/SKILL.md", "---\nname: test_skill\ndescription: 'Core build, test, release, and maintenance workflow for the test repo.'\nallowed-tools:\n  - Bash\n---\n\n<!-- GENERATED BY hg-skill-surface-sync.sh FROM .agents/skills/test_skill/SKILL.md; DO NOT EDIT -->\n\nCompatibility mirror of the canonical `test_skill` skill.\n\n\n# Test\n")
	writeAuditFile(t, dir, ".claude/skills/test-skill/SKILL.md", "---\nname: test-skill\ndescription: 'Hyphenated compatibility alias for the test_skill workflow.'\nallowed-tools:\n  - Bash\n---\n\n<!-- GENERATED BY hg-skill-surface-sync.sh FROM .agents/skills/test_skill/SKILL.md; DO NOT EDIT -->\n\nCompatibility alias for the canonical `test_skill` skill.\n\n\n# Test\n")
}

